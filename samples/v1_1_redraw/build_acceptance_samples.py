def _make_synthetic_source(path, title):
    """Create a clearly marked synthetic placeholder source image (not a real scanned exam)."""
    im = Image.new('RGB', (420, 280), (235, 235, 235))
    draw = ImageDraw.Draw(im)
    draw.rectangle((14, 14, 406, 266), outline=(80, 80, 80), width=2)
    draw.text((28, 120), f'[SYNTHETIC SOURCE PLACEHOLDER: {title}]', fill=(40, 40, 40))
    im.save(path, format='PNG', dpi=(150, 150))
    return path


def _fill(tpl):
    out = deepcopy(tpl)
    for row in out['reviews']:
        row['status'] = 'pass'
        row['checks'] = {k: True for k in CHECKS}
        row['notes'] = ['synthetic acceptance sample generated by build_acceptance_samples.py']
    return out


